func TestRoundAndFinalize256TestRoundAndFinalize256(t *testing.T) {
	for _, tc := range roundAndFinalize256Tcs {
		x := u256Of(bigStr(strings.ReplaceAll(tc.str256, "_", "")))
		if got := d128_format(finalize_256_ctxnull(tc.sign, tc.qExpIn, x, tc.residue, tc.rounding, nil), const_FORMAT_COEFFICIENT_QEXP); got != tc.expected {
			t.Errorf("%s: got %s, expected %s", tc.tag, got, tc.expected)
		}
		if tc.rounding != const_ROUND_TIES_TO_EVEN {
			continue
		}
		if got := d128_format(finalize_256_ctxnull(tc.sign, tc.qExpIn, x, tc.residue, const_ROUND_TIES_TO_EVEN, nil), const_FORMAT_COEFFICIENT_QEXP); got != tc.expected {
			t.Errorf("%s (quiet): got %s, expected %s", tc.tag, got, tc.expected)
		}
	}
}
