func TestU256DivPow10TestU256DivPow10(t *testing.T) {
	for _, tc := range u256DivPow10Tcs {
		qr := div_256_pow10_q128res(u256Of(bigStr(tc.dividend)), tc.pow10)
		if big128(qr.quotDw0, qr.quotDw1).Cmp(bigStr(tc.quotient)) != 0 {
			t.Errorf("quotient mismatch: dividend=%s pow10=%d", tc.dividend, tc.pow10)
		}
		if qr.residue != tc.residue {
			t.Errorf("residue mismatch: dividend=%s pow10=%d", tc.dividend, tc.pow10)
		}
	}
}
